// Every string in the app, in both languages.
//
// Two rules, both about the reason this file is one file and not one file per
// language:
//
//   * KEYS ARE STRUCTURED NAMES, NOT SENTENCES. `goal.field_title` is a name; it
//     is never assembled from fragments. Sentences cannot be translated if their
//     parts are separate, and an Arabic sentence puts the verb where English puts
//     the object — the whole reason there are two languages here is that the
//     layout reverses, and a fragmented string cannot reverse.
//   * NUMBERS ARE INTERPOLATED, NEVER PLURALISED. There is no `t("…", {count})`
//     with a plural table anywhere in this app. Arabic has six plural forms per
//     noun and two entirely different counting systems ("two" is a different
//     shape from "one"), and a hand-built count that is wrong for one language
//     is the kind of wrong nobody reports. So a count is always shown as a
//     number beside its label — "12 Questions" / "12 سؤال" — which is correct in
//     both, and which is also how the tables are read.
//
// `{name}` is the only placeholder. `t()` does the substitution itself rather
// than returning a function, so a missing argument is visible at the call site.

